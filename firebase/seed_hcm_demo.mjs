async function main() {
  console.log('=== Starting HarvestHub Ho Chi Minh Demo Data Seeding ===');

  // Step 1: Login as Admin
  console.log('1. Authenticating as HarvestHub Admin...');
  const adminCred = await signInWithEmailAndPassword(auth, 'admin@harvesthub.app', 'Admin@123');
  console.log('   Authenticated Admin UID:', adminCred.user.uid);

  // Step 2: Seed Categories with Images
  console.log('2. Updating Categories with high-res imagery...');
  const catBatch = writeBatch(db);
  for (const cat of categoriesData) {
    const ref = doc(db, 'categories', cat.id);
    catBatch.set(ref, {
      name: cat.name,
      imageUrl: cat.imageUrl,
      sortOrder: cat.sortOrder,
      isActive: true
    }, { merge: true });
  }
  await catBatch.commit();
  console.log('   Categories updated successfully.');

  // Step 3: Create Farmer Accounts and Profiles
  console.log('3. Setting up 12 Ho Chi Minh City Farmers...');
  const farmerUidMap = new Map();

  for (const farm of hcmFarms) {
    let uid;
    try {
      const userCred = await createUserWithEmailAndPassword(auth, farm.email, 'Farmer@123');
      uid = userCred.user.uid;
      console.log(`   Created new Auth user for ${farm.businessName}: ${uid}`);
    } catch (err) {
      if (err.code === 'auth/email-already-in-use') {
        const userCred = await signInWithEmailAndPassword(auth, farm.email, 'Farmer@123');
        uid = userCred.user.uid;
        console.log(`   Reusing existing Auth user for ${farm.businessName}: ${uid}`);
      } else {
        throw err;
      }
    }

    farmerUidMap.set(farm.key, { uid, businessName: farm.businessName });

    // Set User Profile
    await setDoc(doc(db, 'users', uid), {
      name: farm.name,
      email: farm.email,
      phone: farm.phone,
      address: farm.address,
      role: 'farmer',
      isActive: true,
      createdAt: serverTimestamp()
    }, { merge: true });

    // Set Farmer Profile
    await setDoc(doc(db, 'farmers', uid), {
      userId: uid,
      businessName: farm.businessName,
      farmerName: farm.name,
      area: farm.area,
      address: farm.address,
      pickupAddress: farm.pickupAddress,
      pickupLocation: new GeoPoint(farm.lat, farm.lng),
      phone: farm.phone,
      description: farm.description,
      operatingHours: farm.operatingHours,
      coverImageUrl: farm.coverImageUrl,
      avatarUrl: farm.avatarUrl,
      rating: farm.rating,
      reviewCount: farm.reviewCount,
      isActive: true,
      createdAt: serverTimestamp(),
      updatedAt: serverTimestamp()
    }, { merge: true });
  }

  // Step 4: Re-authenticate as Admin to insert products
  await signInWithEmailAndPassword(auth, 'admin@harvesthub.app', 'Admin@123');

  // Step 5: Insert ~102 Products
  console.log(`4. Inserting ${rawProducts.length} high-quality farm products...`);
  
  // Write products in batches of 25 (Firestore batch limit is 500)
  const chunkSize = 25;
  for (let i = 0; i < rawProducts.length; i += chunkSize) {
    const chunk = rawProducts.slice(i, i + chunkSize);
    const batch = writeBatch(db);

    for (let j = 0; j < chunk.length; j++) {
      const p = chunk[j];
      const index = i + j + 1;
      const farmerInfo = farmerUidMap.get(p.farmKey);
      if (!farmerInfo) {
        throw new Error(`Farmer key not found: ${p.farmKey}`);
      }

      const prodId = `hcm-prod-${String(index).padStart(3, '0')}`;
      const prodRef = doc(db, 'products', prodId);

      batch.set(prodRef, {
        name: p.name,
        farmerId: farmerInfo.uid,
        farmerName: farmerInfo.businessName,
        categoryId: p.categoryId,
        description: p.description,
        price: p.price,
        unit: p.unit,
        stockQty: p.stockQty,
        imageUrl: p.imageUrl,
        imageUrls: p.gallery || [p.imageUrl],
        rating: p.rating,
        reviewCount: p.reviewCount,
        isActive: true,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp()
      });
    }

    await batch.commit();
    console.log(`   Committed products ${i + 1} to ${Math.min(i + chunkSize, rawProducts.length)}`);
  }

  console.log('=== All HCM Demo Data Successfully Seeded! ===');
  console.log(`Summary:`);
  console.log(`- 6 Categories updated with high-resolution imagery`);
  console.log(`- 12 Farmers created around Ho Chi Minh City & Tan Son Nhat Airport`);
  console.log(`- ${rawProducts.length} Fresh agricultural products created with rich images and ratings`);
}

main().catch((err) => {
  console.error('Seeding error:', err);
  process.exit(1);
});
